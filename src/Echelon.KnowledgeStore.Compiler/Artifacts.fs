namespace Echelon.KnowledgeStore.Compiler

open System
open System.IO
open System.Text.Json
open Echelon.KnowledgeStore

/// Freshness of compiled artefacts against the current sources.
type Freshness =
    | Fresh
    | Stale of changed: string list

[<RequireQualifiedAccess>]
module Artifacts =

    let private opts = JsonSerializerOptions(WriteIndented = true)

    let private levelName =
        function
        | Level.Error -> "error"
        | Level.Warning -> "warning"
        | Level.Advisory -> "advisory"
        | Level.RequiresReview -> "requires-review"

    let diagnosticsJson (c: Compilation) =
        c.Diagnostics
        |> List.map (fun d ->
            {|
                code = d.Code
                level = levelName d.Level
                record = d.Record |> Option.toObj
                repository = d.Location |> Option.map _.Repository |> Option.toObj
                path = d.Location |> Option.map _.Path |> Option.toObj
                line = d.Location |> Option.map _.Line |> Option.defaultValue 0
                message = d.Message
                remediation = d.Remediation
            |})
        |> fun xs -> JsonSerializer.Serialize(xs, opts)

    /// Generated outputs (name, content). Deterministic for identical inputs.
    let outputs (c: Compilation) : (string * string) list =
        let records = c.Records |> List.sortBy Graph.key

        let index =
            records |> List.map (Graph.key >> Context.card c.Graph) |> String.concat "\n\n"

        let precomputed =
            {|
                current = c.Precomputed.Current |> Map.filter (fun k v -> k <> v)
                impact = c.Precomputed.Impact |> Map.filter (fun _ m -> not m.IsEmpty)
                evidence =
                    c.Precomputed.Evidence
                    |> Map.filter (fun _ (s, x) -> not (s.IsEmpty && x.IsEmpty))
                    |> Map.map (fun _ (s, x) -> {| supporting = s; contradicting = x |})
                dependencies = c.Precomputed.Dependencies |> Map.filter (fun _ s -> not s.IsEmpty)
            |}

        [
            "index.md",
            "<!-- generated by eks-compiler; do not edit -->\n# Record index\n\n"
            + index
            + "\n"
            "records.jsonl", Codec.toJsonl (records |> List.map Codec.core) + "\n"
            "diagnostics.json", diagnosticsJson c + "\n"
            "precomputed.json", JsonSerializer.Serialize(precomputed, opts) + "\n"
        ]

    /// Manifest: inputs with hashes, outputs with hashes, counts and status.
    let manifest (c: Compilation) (outs: (string * string) list) =
        let count level =
            c.Diagnostics |> List.filter (fun d -> d.Level = level) |> List.length

        {|
            schema = "eks.compilation/0"
            compiler =
                {|
                    name = Pipeline.compilerName
                    version = Pipeline.compilerVersion
                |}
            asOf = c.Config.AsOf.ToString "yyyy-MM-dd"
            inputsHash = c.InputsHash
            inputs =
                c.Units
                |> List.map (fun u ->
                    {|
                        repository = u.File.Repository
                        path = u.File.Path
                        sha256 = u.File.Hash
                    |})
            outputs =
                outs
                |> List.map (fun (n, t) ->
                    {|
                        path = n
                        sha256 = Pipeline.sha256 t
                    |})
            counts =
                {|
                    records = c.Records.Length
                    edges = c.Graph.Edges.Length
                    errors = count Level.Error
                    warnings = count Level.Warning
                    advisories = count Level.Advisory
                    reviews = count Level.RequiresReview
                |}
            status =
                (if Pipeline.hasErrors c then
                     "compiled-with-errors"
                 else
                     "clean")
            note = "Compilation success is structural validity, not factual correctness."
        |}
        |> fun m -> JsonSerializer.Serialize(m, opts) + "\n"

    /// Writes outputs and manifest into `dir`.
    let write (dir: string) (c: Compilation) =
        Directory.CreateDirectory dir |> ignore
        let outs = outputs c

        for name, text in outs do
            File.WriteAllText(Path.Combine(dir, name), text)

        File.WriteAllText(Path.Combine(dir, "manifest.json"), manifest c outs)

    /// Compares a manifest's inputs with the current sources.
    let freshness (manifestJson: string) (current: SourceFile list) : Freshness =
        use doc = JsonDocument.Parse manifestJson

        let recorded =
            doc.RootElement.GetProperty("inputs").EnumerateArray()
            |> Seq.map (fun e ->
                $"""{e.GetProperty("repository").GetString()}/{e.GetProperty("path").GetString()}""",
                e.GetProperty("sha256").GetString() |> string)
            |> Map.ofSeq

        let now =
            current |> List.map (fun f -> $"{f.Repository}/{f.Path}", f.Hash) |> Map.ofList

        let changed =
            (Set.union (recorded |> Map.keys |> Set.ofSeq) (now |> Map.keys |> Set.ofSeq))
            |> Set.filter (fun k -> Map.tryFind k recorded <> Map.tryFind k now)
            |> Set.toList

        if changed.IsEmpty then Fresh else Stale changed
